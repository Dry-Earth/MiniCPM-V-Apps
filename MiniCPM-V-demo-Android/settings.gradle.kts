pluginManagement {
    // Aliyun is the right default for a China-side build, but it is flaky from
    // GitHub's runners, so CI flips the preference instead of dropping it.
    val preferCn = (System.getenv("MINICPMV_CN_MIRRORS") ?: "true").toBoolean()
    repositories {
        if (preferCn) {
            maven { url = uri("https://maven.aliyun.com/repository/google") }
            maven { url = uri("https://maven.aliyun.com/repository/public") }
            maven { url = uri("https://maven.aliyun.com/repository/gradle-plugin") }
        }
        google {
            content {
                includeGroupByRegex("com\\.android.*")
                includeGroupByRegex("com\\.google.*")
                includeGroupByRegex("androidx.*")
            }
        }
        mavenCentral()
        gradlePluginPortal()
        if (!preferCn) {
            maven { url = uri("https://maven.aliyun.com/repository/google") }
            maven { url = uri("https://maven.aliyun.com/repository/public") }
            maven { url = uri("https://maven.aliyun.com/repository/gradle-plugin") }
        }
    }
}
